// Helper functions for search and filtering
export function searchNovels(query: string, novels = MOCK_NOVELS): typeof MOCK_NOVELS {
  const lowerQuery = query.toLowerCase();
  return novels.filter(
    (novel) =>
      novel.title.toLowerCase().includes(lowerQuery) ||
      novel.authorName.toLowerCase().includes(lowerQuery)
  );
}

export function filterByGenre(genreName: string, novels = MOCK_NOVELS): typeof MOCK_NOVELS {
  return novels.filter((novel) => novel.genreName === genreName);
}

export function filterByStatus(
  status: 'ONGOING' | 'COMPLETED' | 'ALL',
  novels = MOCK_NOVELS
): typeof MOCK_NOVELS {
  if (status === 'ALL') return novels;
  return novels.filter((novel) => novel.status === status);
}

export type SortType = 'latest' | 'views' | 'popular';
export function sortNovels(novels: typeof MOCK_NOVELS, sortType: SortType): typeof MOCK_NOVELS {
  const sorted = [...novels];
  switch (sortType) {
    case 'latest':
      return sorted.reverse();
    case 'views':
      return sorted.sort((a, b) => b.totalViews - a.totalViews);
    case 'popular':
      return sorted.sort((a, b) => {
        const scoreA = a.totalViews + a.totalEpisodes * 100;
        const scoreB = b.totalViews + b.totalEpisodes * 100;
        return scoreB - scoreA;
      });
    default:
      return sorted;
  }
}

export type RankingType = 'overall' | 'byGenre' | 'trending' | 'new' | 'completed';
export type RankingPeriod = 'daily' | 'weekly' | 'monthly' | 'all';

export function generateRanking(
  rankingType: RankingType,
  genreFilter?: string
): Array<{
  rank: number;
  rankChange?: number;
  novel: (typeof MOCK_NOVELS)[0];
}> {
  let filteredNovels = MOCK_NOVELS;

  if (rankingType === 'byGenre' && genreFilter) {
    filteredNovels = filterByGenre(genreFilter, MOCK_NOVELS);
  } else if (rankingType === 'trending') {
    filteredNovels = MOCK_NOVELS.filter((n) => n.status === 'ONGOING');
  } else if (rankingType === 'new') {
    filteredNovels = [...MOCK_NOVELS].reverse().slice(0, 20);
  } else if (rankingType === 'completed') {
    filteredNovels = MOCK_NOVELS.filter((n) => n.status === 'COMPLETED');
  }

  const sorted = sortNovels(filteredNovels, 'views');

  return sorted.slice(0, 100).map((novel, index) => ({
    rank: index + 1,
    rankChange: ((index * 7 + 3) % 5) - 2,
    novel,
  }));
}

export function getRelatedNovels(novelId: string, limit = 5): typeof MOCK_NOVELS {
  const novel = MOCK_NOVELS.find((n) => n.id === novelId);
  if (!novel) return [];

  return MOCK_NOVELS.filter((n) => n.id !== novelId && n.genreName === novel.genreName).slice(
    0,
    limit
  );
}

